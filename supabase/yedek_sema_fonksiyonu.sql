-- Sistem Yedeği sayfasının kullandığı fonksiyon: public şemasının yapısını (tablolar, kısıtlar, indeksler,
-- RLS politikaları, fonksiyonlar, tetikleyiciler, görünümler, yetkiler, storage kovaları) çalıştırılabilir SQL olarak üretir.
-- Sadece OKUR; hiçbir veriyi veya yapıyı değiştirmez. Yalnızca service_role çağırabilir (anon/authenticated kapalı).
-- Adı bilerek rpc_ ile başlamaz: /api/erp proxy'sinin rpc_* izin listesine girmesin.
-- Yeni bir Supabase projesine taşırken bu dosyayı da çalıştırın ki Sistem Yedeği sayfası orada da çalışsın.

create or replace function public.yedek_sema_olustur()
returns text
language plpgsql
security definer
set search_path = pg_catalog
as $fn$
declare
  r record;
  a record;
  s text := '';
  nl text := E'\n';
  sem text;
  semalar text[];
begin
  -- public dışındaki kullanıcı şemaları (ör. private: RLS politikalarının kullandığı yardımcı fonksiyonlar)
  select coalesce(array_agg(n.nspname order by n.nspname), '{}'::text[]) into semalar
  from pg_namespace n
  where n.nspname <> 'public' and n.nspname not like 'pg\_%'
    and n.nspname not in ('information_schema','auth','storage','extensions','graphql','graphql_public','vault','realtime','pgsodium','pgsodium_masks','net','supabase_functions','supabase_migrations','cron','pgbouncer','_realtime','_analytics');

  s := '-- Alya veritabanı yapısı yedeği' || nl
    || '-- Oluşturulma: ' || now()::text || nl
    || '-- Veriler tablolar/*.json|csv dosyalarındadır; auth.users kayıtları ve depolama dosyaları ayrıca taşınır.' || nl
    || '-- Sırası: eklentiler, tipler, tablolar, fonksiyonlar, varsayılanlar, kısıtlar, indeksler, görünümler, RLS, tetikleyiciler, yetkiler.' || nl
    || '-- Boş bir projede önce bu dosyayı, sonra verileri yükleyin. Üretilmiş dosyadır; ilk kullanımda boş projede deneyin.' || nl
    || 'set check_function_bodies = false;' || nl || nl;

  -- 1) Eklentiler
  for r in select e.extname, n.nspname from pg_extension e join pg_namespace n on n.oid = e.extnamespace where e.extname <> 'plpgsql' order by e.extname loop
    s := s || format('create extension if not exists %I with schema %I;', r.extname, r.nspname) || nl;
  end loop;

  -- 1b) Ek şemalar ve kullanım yetkileri
  foreach sem in array semalar loop
    s := s || format('create schema if not exists %I;', sem) || nl;
    for a in
      select distinct g.rolname from pg_namespace n
      cross join lateral aclexplode(n.nspacl) x
      join pg_roles g on g.oid = x.grantee
      where n.nspname = sem and x.privilege_type = 'USAGE' and g.rolname in ('anon', 'authenticated', 'service_role')
      order by g.rolname
    loop
      s := s || format('grant usage on schema %I to %I;', sem, a.rolname) || nl;
    end loop;
  end loop;

  -- 2) Enum tipleri
  for r in
    select t.typname, string_agg(quote_literal(e.enumlabel), ', ' order by e.enumsortorder) as etiketler
    from pg_type t join pg_enum e on e.enumtypid = t.oid join pg_namespace n on n.oid = t.typnamespace
    where n.nspname = 'public' group by t.typname order by t.typname
  loop
    s := s || format('create type public.%I as enum (%s);', r.typname, r.etiketler) || nl;
  end loop;

  -- 3) Sıra (sequence) nesneleri
  for r in select sequencename from pg_sequences where schemaname = 'public' order by sequencename loop
    s := s || format('create sequence if not exists public.%I;', r.sequencename) || nl;
  end loop;

  -- 4) Tablolar (varsayılan değerler fonksiyonlardan sonra eklenir)
  s := s || nl;
  for r in
    select c.oid, c.relname from pg_class c join pg_namespace n on n.oid = c.relnamespace
    where n.nspname = 'public' and c.relkind = 'r' order by c.relname
  loop
    s := s || format('create table public.%I (', r.relname) || nl || (
      select string_agg(
        format('  %I %s%s%s', at.attname, format_type(at.atttypid, at.atttypmod),
          case
            when at.attidentity = 'a' then ' generated always as identity'
            when at.attidentity = 'd' then ' generated by default as identity'
            when at.attgenerated = 's' then ' generated always as (' || pg_get_expr(d.adbin, d.adrelid) || ') stored'
            else ''
          end,
          case when at.attnotnull then ' not null' else '' end),
        E',\n' order by at.attnum)
      from pg_attribute at left join pg_attrdef d on d.adrelid = at.attrelid and d.adnum = at.attnum
      where at.attrelid = r.oid and at.attnum > 0 and not at.attisdropped
    ) || nl || ');' || nl;
  end loop;

  -- 5) Fonksiyonlar ve yetkileri
  s := s || nl;
  for r in
    select p.oid, pg_get_functiondef(p.oid) as def, p.oid::regprocedure::text as imza, p.proacl
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace
    where (n.nspname = 'public' or n.nspname = any(semalar)) and p.prokind in ('f', 'p')
      and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
    order by n.nspname, p.proname, p.oid
  loop
    s := s || r.def || ';' || nl;
    if r.proacl is not null then
      s := s || format('revoke all on function %s from public, anon, authenticated, service_role;', r.imza) || nl;
      for a in select distinct x.grantee from aclexplode(r.proacl) x where x.privilege_type = 'EXECUTE' loop
        s := s || format('grant execute on function %s to %s;', r.imza,
          case when a.grantee = 0 then 'public' else (select quote_ident(rolname) from pg_roles where oid = a.grantee) end) || nl;
      end loop;
    end if;
  end loop;

  -- 6) Varsayılan değerler
  s := s || nl;
  for r in
    select c.relname, at.attname, pg_get_expr(d.adbin, d.adrelid) as ifade
    from pg_attrdef d
    join pg_attribute at on at.attrelid = d.adrelid and at.attnum = d.adnum
    join pg_class c on c.oid = d.adrelid join pg_namespace n on n.oid = c.relnamespace
    where n.nspname = 'public' and c.relkind = 'r' and at.attgenerated = '' and at.attidentity = ''
    order by c.relname, at.attnum
  loop
    s := s || format('alter table public.%I alter column %I set default %s;', r.relname, r.attname, r.ifade) || nl;
  end loop;

  -- 7) Birincil anahtar / benzersiz / kontrol kısıtları, sonra yabancı anahtarlar
  s := s || nl;
  for r in
    select c.relname, k.conname, pg_get_constraintdef(k.oid) as tanim
    from pg_constraint k join pg_class c on c.oid = k.conrelid
    where k.connamespace = 'public'::regnamespace and k.contype in ('p', 'u', 'c')
    order by case k.contype when 'p' then 1 when 'u' then 2 else 3 end, c.relname, k.conname
  loop
    s := s || format('alter table public.%I add constraint %I %s;', r.relname, r.conname, r.tanim) || nl;
  end loop;
  for r in
    select c.relname, k.conname, pg_get_constraintdef(k.oid) as tanim
    from pg_constraint k join pg_class c on c.oid = k.conrelid
    where k.connamespace = 'public'::regnamespace and k.contype = 'f'
    order by c.relname, k.conname
  loop
    s := s || format('alter table public.%I add constraint %I %s;', r.relname, r.conname, r.tanim) || nl;
  end loop;

  -- 8) İndeksler (kısıtlarla gelenler hariç)
  s := s || nl;
  for r in
    select i.indexdef from pg_indexes i
    where i.schemaname = 'public'
      and i.indexname not in (select conname from pg_constraint where connamespace = 'public'::regnamespace and contype in ('p', 'u'))
    order by i.tablename, i.indexname
  loop
    s := s || r.indexdef || ';' || nl;
  end loop;

  -- 9) Tablo ve sütun açıklamaları
  s := s || nl;
  for r in
    select c.relname, d.objsubid, d.description,
           (select attname from pg_attribute where attrelid = c.oid and attnum = d.objsubid) as sutun
    from pg_description d join pg_class c on c.oid = d.objoid and d.classoid = 'pg_class'::regclass
    join pg_namespace n on n.oid = c.relnamespace
    where n.nspname = 'public' and c.relkind = 'r'
    order by c.relname, d.objsubid
  loop
    if r.objsubid = 0 then
      s := s || format('comment on table public.%I is %L;', r.relname, r.description) || nl;
    elsif r.sutun is not null then
      s := s || format('comment on column public.%I.%I is %L;', r.relname, r.sutun, r.description) || nl;
    end if;
  end loop;

  -- 10) Görünümler (oluşturulma sırasıyla)
  s := s || nl;
  for r in
    select c.relname, c.reloptions, pg_get_viewdef(c.oid, true) as tanim
    from pg_class c join pg_namespace n on n.oid = c.relnamespace
    where n.nspname = 'public' and c.relkind = 'v' order by c.oid
  loop
    s := s || format('create or replace view public.%I%s as', r.relname,
      case when r.reloptions is not null then ' with (' || array_to_string(r.reloptions, ', ') || ')' else '' end) || nl || r.tanim || nl;
  end loop;

  -- 11) RLS ve politikalar (public + storage.objects)
  s := s || nl;
  for r in
    select c.relname, c.relforcerowsecurity from pg_class c join pg_namespace n on n.oid = c.relnamespace
    where n.nspname = 'public' and c.relkind = 'r' and c.relrowsecurity order by c.relname
  loop
    s := s || format('alter table public.%I enable row level security;', r.relname) || nl;
    if r.relforcerowsecurity then s := s || format('alter table public.%I force row level security;', r.relname) || nl; end if;
  end loop;
  for r in select * from pg_policies where schemaname in ('public', 'storage') order by schemaname, tablename, policyname loop
    s := s || format('create policy %I on %I.%I as %s for %s to %s%s%s;', r.policyname, r.schemaname, r.tablename,
      lower(r.permissive), r.cmd, array_to_string(r.roles, ', '),
      coalesce(' using (' || r.qual || ')', ''), coalesce(' with check (' || r.with_check || ')', '')) || nl;
  end loop;

  -- 12) Tetikleyiciler (public tabloları + auth.users üzerindekiler)
  s := s || nl;
  for r in
    select pg_get_triggerdef(t.oid) as tanim
    from pg_trigger t join pg_class c on c.oid = t.tgrelid join pg_namespace n on n.oid = c.relnamespace
    where not t.tgisinternal and (n.nspname = 'public' or (n.nspname = 'auth' and c.relname = 'users'))
      and not exists (select 1 from pg_depend d where d.objid = t.oid and d.deptype = 'e')
    order by n.nspname, c.relname, t.tgname
  loop
    s := s || r.tanim || ';' || nl;
  end loop;

  -- 13) Tablo / görünüm yetkileri (anon, authenticated, service_role)
  s := s || nl;
  for r in
    select c.relname, g.rolname, string_agg(x.privilege_type, ', ' order by x.privilege_type) as yetkiler
    from pg_class c join pg_namespace n on n.oid = c.relnamespace
    cross join lateral aclexplode(c.relacl) x
    join pg_roles g on g.oid = x.grantee
    where n.nspname = 'public' and c.relkind in ('r', 'v') and g.rolname in ('anon', 'authenticated', 'service_role') and x.privilege_type <> 'MAINTAIN'
    group by c.relname, g.rolname order by c.relname, g.rolname
  loop
    s := s || format('grant %s on public.%I to %I;', r.yetkiler, r.relname, r.rolname) || nl;
  end loop;

  -- 14) Storage kovaları
  s := s || nl;
  for r in select id, name, public, file_size_limit, allowed_mime_types from storage.buckets order by id loop
    s := s || format('insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types) values (%L, %L, %L, %s, %s) on conflict (id) do nothing;',
      r.id, r.name, r.public, coalesce(r.file_size_limit::text, 'null'),
      case when r.allowed_mime_types is null then 'null' else quote_literal(r.allowed_mime_types::text) || '::text[]' end) || nl;
  end loop;

  -- 15) Sıra değerleri (verileri yükledikten sonra çalıştırın)
  s := s || nl || '-- Verileri yükledikten sonra çalıştırın:' || nl;
  for r in select sequencename, last_value, start_value from pg_sequences where schemaname = 'public' order by sequencename loop
    s := s || format('select setval(%L, %s, %s);', 'public.' || r.sequencename, coalesce(r.last_value, r.start_value), (r.last_value is not null)::text) || nl;
  end loop;

  return s;
end
$fn$;

revoke all on function public.yedek_sema_olustur() from public, anon, authenticated;
grant execute on function public.yedek_sema_olustur() to service_role;
